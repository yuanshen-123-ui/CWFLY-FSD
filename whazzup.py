"""Whazzup status file generator.

Generates the whazzup.txt file with client/server status information,
compatible with FSD clients.
"""

import asyncio
import logging
import os
import time
from typing import Optional

from protocol import CLIENT_ATC, CLIENT_PILOT

logger = logging.getLogger("fsd.whazzup")

WHAZZUP_INTERVAL = 30  # seconds


class WhazzupGenerator:
    """Generates whazzup.txt status files at regular intervals."""

    def __init__(self, server):
        self.server = server
        self._task: Optional[asyncio.Task] = None
        self._running = False

    def start(self):
        self._running = True
        self._task = asyncio.create_task(self._run_loop())
        logger.info("Whazzup generator started")

    def stop(self):
        self._running = False
        if self._task:
            self._task.cancel()

    async def _run_loop(self):
        """Generate whazzup file every 30 seconds."""
        while self._running:
            try:
                self._generate()
            except Exception as e:
                logger.error(f"Whazzup generation error: {e}")
            await asyncio.sleep(WHAZZUP_INTERVAL)

    @staticmethod
    def _is_system_callsign(callsign: str) -> bool:
        """判断是否为系统连接（bot/tracker/FP 提交器），应从在线统计中排除。

        系统客户端统一使用 CW- 前缀：CW-BOT、CW-MAP-xxx、CW-FPxxx。
        """
        cs = (callsign or "").upper()
        return cs.startswith("CW-")

    def _generate(self):
        """Write the whazzup.txt file."""
        filename = self.server.config.whazzup_file
        if not filename:
            return

        # Use temp file for atomic replace
        tmpfile = filename + ".tmp"

        try:
            with open(tmpfile, "w") as f:
                now = time.time()
                tm = time.gmtime(now)

                # Header
                f.write(f"; Whazzup file generated by {self.server.ident}\r\n")
                f.write(f"!GENERAL\r\n")
                f.write(f"VERSION = {self.server.ident}\r\n")
                f.write(f"RELOAD = {WHAZZUP_INTERVAL}\r\n")
                f.write(f"UPDATE = {time.strftime('%Y-%m-%dT%H:%M:%SZ', tm)}\r\n")

                # 过滤系统连接（bot/tracker/FP 提交器），只统计真实机组与管制员
                real_clients = [
                    (cs, h) for cs, h in self.server.clients.items()
                    if not self._is_system_callsign(cs)
                ]
                f.write(f"CONNECTED CLIENTS = {len(real_clients)}\r\n")
                f.write(f"CONNECTED SERVERS = {len(self.server.server_links.links)}\r\n")

                # Clients section
                f.write(f"!CLIENTS\r\n")
                for cs, handler in sorted(real_clients):
                    c = handler.client
                    if not c:
                        continue

                    ctype = "ATC" if c.type == CLIENT_ATC else "PILOT"

                    # Segment 1: callsign:cid:realname:type
                    seg1 = f"{c.callsign}:{c.cid}:{c.realname}:{ctype}"

                    # Segment 2: frequency
                    if c.type == CLIENT_ATC and c.frequency:
                        # frequency 已由 % 包转换为 MHz（如 120.600）；
                        # 仅在确实以 Hz 存储（>1000）时才换算，避免再除 1000 得到 0.121
                        freq_mhz = c.frequency / 1000.0 if c.frequency > 1000 else c.frequency
                        seg2 = f"{freq_mhz:.3f}"
                    else:
                        seg2 = ""

                    # Segment 3: lat:lon:alt:gs
                    if c.lat or c.lon:
                        seg3 = f"{c.lat}:{c.lon}:{c.altitude}:{c.groundspeed}"
                    else:
                        seg3 = ":::"

                    # Segment 4: flight plan info
                    if c.plan:
                        fp = c.plan
                        seg4 = (f"{fp.aircraft}:{fp.tascruise}:{fp.depairport}:"
                                f"{fp.altitude}:{fp.destairport}")
                    else:
                        seg4 = "::::"

                    # Segment 5: location:protocol:rating:transponder:facility:visrange
                    seg5 = f"{self.server.location}:{c.protocol}:{c.rating}:{c.transponder}:{c.facility_type}:{c.visual_range}"

                    # Segment 6: flight plan extended
                    if c.plan:
                        fp = c.plan
                        seg6 = (f"{fp.revision}:{fp.type}:{fp.deptime}:{fp.actdeptime}:"
                                f"{fp.hrsenroute}:{fp.minenroute}:{fp.hrsfuel}:{fp.minfuel}:"
                                f"{fp.altairport}:{fp.remarks}:{fp.route}")
                    else:
                        seg6 = "0:I:0:0:0:0:0:0::::"

                    # Segment 7: time
                    seg7 = f"::::::{time.strftime('%Y%m%d%H%M%S', time.gmtime(c.start_time))}"

                    f.write(f"{seg1}:{seg2}:{seg3}:{seg4}:{seg5}:{seg6}:{seg7}\r\n")

                # Servers section
                f.write(f"!SERVERS\r\n")
                f.write(f"{self.server.ident}:{self.server.hostname}:"
                       f"{self.server.location}:{self.server.name}:1\r\n")

            # Atomic rename
            if os.path.exists(filename):
                os.remove(filename)
            os.rename(tmpfile, filename)

        except Exception as e:
            logger.error(f"Failed to write whazzup: {e}")
            try:
                if os.path.exists(tmpfile):
                    os.remove(tmpfile)
            except Exception:
                pass
